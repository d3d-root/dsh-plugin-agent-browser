// Зачем один файл вместо `node --test test/a.mjs test/b.mjs`:
//   * `node --test` с несколькими файлами порождает дочерние процессы, а в
//     песочнице это блокируется (spawn EPERM) — тесты не запускаются вовсе;
//   * цепочка `&&` не работает в Windows PowerShell 5.1.
// Здесь все файлы импортируются в один процесс: работает и в CI, и локально,
// в любой оболочке. Каждый файл по-прежнему можно запустить отдельно.
//
// Запуск: node --test-force-exit test/all.test.mjs

